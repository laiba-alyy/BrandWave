def enrich_keywords(
    db: Session,
    keywords: list[str],
    country: str,
    language: str = "en",
    *,
    want_related: bool = False,
    always_fresh: set[str] | None = None,
) -> EnrichmentResult:
    """
    Candidates ko asli market data se enrich karo. RAISE KABHI NAHI karta.

    Teen endpoints, teen alag alag faisle: volume na mile to poora enrichment
    nakaam mana jata hai (wahi asal cheez hai jo user maangta hai). Difficulty
    ya intent na milen to baqi data phir bhi wapis jata hai — Labs subscription
    alag hoti hai, aur aadha data na-hone se behtar hai.

    `always_fresh`: wo keywords jinhe local metric cache se SERVE nahi karna,
    chahe wahan maujood hon — brand-specific keywords ("maria b eid
    collection"). Wo har brand ke apne hain aur un ki demand seasons ke saath
    hilti rehti hai, is liye unhe stale data se jawab dena ghalat hota. Likha
    phir bhi jata hai (aana wala run us se bhi shuru kar sake).

    NOTE: filter yahan lagta hai, alag call mein nahi — Google Ads ka search
    volume PER REQUEST charge hota hai ($0.09), per keyword nahi. Do call
    karne se lagat dugni ho jati, ek call mein sab bhejne se nahi.
    """
    always_fresh = always_fresh or set()
    normalized = list(dict.fromkeys(
        normalize_keyword(k) for k in keywords if (k or "").strip()
    ))[:MAX_KEYWORDS]
    if not normalized:
        return EnrichmentResult(available=False, reason="no keywords to enrich")

    if not is_configured():
        return EnrichmentResult(
            available=False,
            reason="DATAFORSEO_LOGIN / DATAFORSEO_PASSWORD not set",
        )

    try:
        country_code = normalize_country(country)
        location = country_name(country_code)
    except Exception as exc:
        return EnrichmentResult(available=False, reason=f"unsupported market: {exc}")

    cacheable = [k for k in normalized if k not in always_fresh]
    cached = _load_cache(db, cacheable, country_code, language) if cacheable else {}
    missing = [k for k in normalized if k not in cached]
    if not missing:
        logger.info("[dataforseo] %d keywords served from cache", len(cached))
        return EnrichmentResult(metrics=cached, available=True, reason="cache")

    metrics: dict[str, KeywordMetrics] = {
        k: KeywordMetrics(keyword=k) for k in missing
    }
    total_cost = 0.0

    # ── 1. Search volume (Google Ads) — ye LAAZMI hai ────────────────────
    try:
        items, cost = _post(SEARCH_VOLUME_URL, [{
            "keywords": missing,
            "location_name": location,
            "language_code": language.lower(),
            "search_partners": False,
        }])
        total_cost += cost
        for item in items:
            keyword = _keyword_of(item)
            if keyword in metrics:
                metrics[keyword].search_volume = item.get("search_volume")
                metrics[keyword].competition_index = item.get("competition_index")
                metrics[keyword].cpc = item.get("cpc")
                competition = item.get("competition")
                # Google Ads kabhi "LOW"/"MEDIUM"/"HIGH" string bhejta hai
                # aur kabhi 0-1 float. Dono ko float par le aao.
                if isinstance(competition, str):
                    competition = {"LOW": 0.15, "MEDIUM": 0.5, "HIGH": 0.85}.get(
                        competition.upper()
                    )
                metrics[keyword].competition = competition
    except _Unavailable as exc:
        logger.warning("DataForSEO credit exhausted, using LLM-only fallback (%s)", exc)
        # Cache mein purana data ho to wo phir bhi qeemti hai.
        if cached:
            return EnrichmentResult(
                metrics=cached, available=True,
                reason=f"partial: live call failed ({exc}), served cache",
            )
        return EnrichmentResult(available=False, reason=str(exc))

    # ── 2. Keyword difficulty (Labs) — na mile to koi baat nahi ──────────
    try:
        items, cost = _post(DIFFICULTY_URL, [{
            "keywords": missing,
            "location_name": location,
            "language_code": language.lower(),
        }])
        total_cost += cost
        for item in items:
            keyword = _keyword_of(item)
            if keyword in metrics:
                value = item.get("keyword_difficulty")
                if value is None:
                    value = _dig(item, "keyword_properties", "keyword_difficulty")
                metrics[keyword].keyword_difficulty = value
    except _Unavailable as exc:
        logger.info("[dataforseo] difficulty unavailable, deriving from competition (%s)", exc)

    # ── 3. Search intent (Labs) — na mile to heuristic chalega ───────────
    try:
        items, cost = _post(INTENT_URL, [{
            "keywords": missing,
            "language_code": language.lower(),
        }])
        total_cost += cost
        for item in items:
            keyword = _keyword_of(item)
            if keyword in metrics:
                label = _dig(item, "keyword_intent", "label") or item.get("intent")
                if label:
                    metrics[keyword].search_intent = str(label).lower()
    except _Unavailable as exc:
        logger.info("[dataforseo] search intent unavailable, using heuristic (%s)", exc)

    related: list[str] = []
    if want_related and missing:
        related = fetch_related(missing[0], country_code, language)

    _save_cache(db, metrics, country_code, language)
    metrics.update(cached)

    logger.info(
        "[dataforseo] enriched %d keywords for %s (cost $%.4f)",
        len(missing), country_code, total_cost,
    )
    return EnrichmentResult(
        metrics=metrics, available=True, reason=None,
        related=related, cost=total_cost,
    )


def fetch_related(seed: str, country: str, language: str = "en", limit: int = 20) -> list[str]:
    """
    Labs se related keywords — wo terms jo LLM ne socha hi nahi.
    Nakami par khali list; ye feature optional hai.
    """
    try:
        location = country_name(normalize_country(country))
        items, _ = _post(RELATED_URL, [{
            "keyword": normalize_keyword(seed),
            "location_name": location,
            "language_code": language.lower(),
            "depth": 1,
            "limit": limit,
        }])
    except _Unavailable as exc:
        logger.info("[dataforseo] related keywords unavailable (%s)", exc)
        return []

    out = []
    for item in items:
        keyword = _keyword_of(item)
        if keyword and keyword != normalize_keyword(seed):
            out.append(keyword)
    return out[:limit]


def account_status() -> dict:
    """
    Chhota health check — UI/logs ke liye "DataForSEO kis haal mein hai".
    Ye endpoint FREE hai (cost 0), is liye ise call karna mehnga nahi.
    """
    if not is_configured():
        return {"configured": False, "usable": False,
                "reason": "DATAFORSEO_LOGIN / DATAFORSEO_PASSWORD not set"}
    try:
        response = httpx.get(f"{BASE}/appendix/user_data",
                             headers=_auth_header(), timeout=TIMEOUT)
        payload = response.json()
        if payload.get("status_code") != 20000:
            return {"configured": True, "usable": False,
                    "reason": payload.get("status_message")}
        result = payload["tasks"][0]["result"]
        result = result[0] if isinstance(result, list) else result
        money = result.get("money") or {}
        return {
            "configured": True,
            "usable": True,
            "balance": money.get("balance"),
            "reason": None,
        }
    except Exception as exc:
        return {"configured": True, "usable": False, "reason": str(exc)}
