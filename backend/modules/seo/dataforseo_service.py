"""
DataForSEO se keyword metrics — aur jab wo dastyab na ho to KHAMOSHI se peeche hatna.

── dataforseo.py se farq ────────────────────────────────────────────────────
`dataforseo.py` (purana) sirf search volume laata hai aur nakami par
DataForSEOError PHENKTA hai — us se route 503 deti hai aur user ko keywords
milte hi nahi.

Ye module us se ooper baithta hai aur do cheezein zyada karta hai:

  1. Volume ke ilawa DIFFICULTY aur SEARCH INTENT bhi (DataForSEO Labs ke do
     alag endpoints se).
  2. KABHI raise nahi karta. Har nakami — 402 payment required, 401 auth,
     403 unverified account, timeout, ya koi bhi cheez — `available=False`
     wala natija banti hai. Caller LLM-only mode par chala jata hai aur
     feature chalta rehta hai (Part 2 ka "NEVER breaks").

── Is account ki maujooda haalat (26 Aug 2026 ko naapi gayi) ────────────────
Balance $1.00 hai (khali nahi), MAGAR har data endpoint 403 deta hai:

    40104  "Please verify your account before using the API.
            You can complete verification in the user panel:
            https://app.dataforseo.com/"

Yani abhi LIVE raasta yehi fallback hai. Verification ke baad ye module bina
kisi code change ke asli metrics dene lagega.

── Asli qeematen (appendix/user_data se, brief ke andaze se bohat kam) ──────
    google_ads/search_volume/live         $0.09  PER REQUEST (per keyword NAHI)
    labs/bulk_keyword_difficulty/live     $0.012 + $0.00012/keyword
    labs/search_intent/live               $0.012 + $0.00012/keyword
    labs/related_keywords/live            $0.012 + $0.00012/result

30 keywords ki poori enrichment ≈ $0.12 — yani $1 credit mein ~8 poore run.
"""

import base64
import logging
import os
from dataclasses import dataclass, field

import httpx
from sqlalchemy.orm import Session

from models.seo_result import SEOKeywordMetricCache
from modules.seo.dataforseo import country_name, normalize_country, normalize_keyword

logger = logging.getLogger(__name__)

BASE = "https://api.dataforseo.com/v3"
SEARCH_VOLUME_URL = f"{BASE}/keywords_data/google_ads/search_volume/live"
DIFFICULTY_URL = f"{BASE}/dataforseo_labs/google/bulk_keyword_difficulty/live"
INTENT_URL = f"{BASE}/dataforseo_labs/google/search_intent/live"
RELATED_URL = f"{BASE}/dataforseo_labs/google/related_keywords/live"

TIMEOUT = 45

# Labs endpoints ek request mein 1,000 keywords tak lete hain; Google Ads 700.
MAX_KEYWORDS = 700

SOURCE_VALIDATED = "DataForSEO Validated"
SOURCE_AI = "AI Suggested"


@dataclass
class KeywordMetrics:
    keyword: str
    search_volume: int | None = None
    competition: float | None = None
    competition_index: int | None = None
    cpc: float | None = None
    keyword_difficulty: int | None = None
    search_intent: str | None = None

    @property
    def has_data(self) -> bool:
        return self.search_volume is not None or self.keyword_difficulty is not None


@dataclass
class EnrichmentResult:
    """
    Enrichment ka natija — kamyab ho ya na ho, SHAKAL EK HI rehti hai.

    `available=False` koi error nahi hai; ye ek maloomat hai jo UI tak jati
    hai ("Keywords generated by AI. Connect DataForSEO for search volume data.").
    """
    metrics: dict[str, KeywordMetrics] = field(default_factory=dict)
    available: bool = False
    reason: str | None = None
    related: list[str] = field(default_factory=list)
    cost: float = 0.0
    # Category-level cache ka hisaab kitab (modules/seo/keyword_cache.py bharta
    # hai). Yahan rakha hai taake caller ko ek hi natija object mein sab mile —
    # "kitne keywords cache se aaye, kitne khareede gaye".
    cache_stats: dict = field(default_factory=dict)

    @property
    def source_label(self) -> str:
        return SOURCE_VALIDATED if self.available else SOURCE_AI


