def _load_cache(db: Session, keywords: list[str], country: str, language: str) -> dict[str, KeywordMetrics]:
    rows = db.query(SEOKeywordMetricCache).filter(
        SEOKeywordMetricCache.normalized_keyword.in_(keywords),
        SEOKeywordMetricCache.country == country.upper(),
        SEOKeywordMetricCache.language == language.lower(),
        SEOKeywordMetricCache.provider == "dataforseo",
    ).all()
    return {
        row.normalized_keyword: KeywordMetrics(
            keyword=row.normalized_keyword,
            search_volume=row.search_volume,
            competition=row.competition,
            competition_index=row.competition_index,
            cpc=row.cpc,
            keyword_difficulty=getattr(row, "keyword_difficulty", None),
            search_intent=getattr(row, "search_intent", None),
        )
        for row in rows
    }


def _save_cache(db: Session, metrics: dict[str, KeywordMetrics], country: str, language: str) -> None:
    """Cache likhna best-effort hai — is par poora keyword flow nahi girna chahiye."""
    try:
        existing = {
            row.normalized_keyword: row
            for row in db.query(SEOKeywordMetricCache).filter(
                SEOKeywordMetricCache.normalized_keyword.in_(list(metrics)),
                SEOKeywordMetricCache.country == country.upper(),
                SEOKeywordMetricCache.language == language.lower(),
                SEOKeywordMetricCache.provider == "dataforseo",
            ).all()
        }
        for keyword, metric in metrics.items():
            if not metric.has_data:
                continue
            row = existing.get(keyword)
            if row is None:
                row = SEOKeywordMetricCache(
                    normalized_keyword=keyword, country=country.upper(),
                    language=language.lower(), provider="dataforseo",
                )
                db.add(row)
            row.search_volume = metric.search_volume
            row.competition = metric.competition
            row.competition_index = metric.competition_index
            row.cpc = metric.cpc
            row.keyword_difficulty = metric.keyword_difficulty
            row.search_intent = metric.search_intent
        db.commit()
    except Exception as exc:
        db.rollback()
        logger.warning("[dataforseo] cache write skipped: %s", exc)


