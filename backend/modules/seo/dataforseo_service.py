def is_configured() -> bool:
    return bool((os.getenv("DATAFORSEO_LOGIN") or "").strip()
                and (os.getenv("DATAFORSEO_PASSWORD") or "").strip())


def _auth_header() -> dict:
    login = (os.getenv("DATAFORSEO_LOGIN") or "").strip()
    password = (os.getenv("DATAFORSEO_PASSWORD") or "").strip()
    token = base64.b64encode(f"{login}:{password}".encode()).decode()
    return {"Authorization": f"Basic {token}", "Content-Type": "application/json"}


class _Unavailable(Exception):
    """Andarooni signal: is call se data nahi mila. Bahar kabhi nahi jata."""


def _post(url: str, body: list) -> tuple[list[dict], float]:
    """
    Ek live endpoint call. Har nakami _Unavailable ban jati hai — yahan se
    koi HTTP ya parse exception bahar nahi nikalti.

    Return: (result_items, cost)
    """
    try:
        response = httpx.post(url, json=body, headers=_auth_header(), timeout=TIMEOUT)
    except Exception as exc:                       # timeout, DNS, TLS, sab
        raise _Unavailable(f"network error: {exc}") from exc

    if response.status_code == 402:
        raise _Unavailable("credit exhausted (402 Payment Required)")
    if response.status_code in (401, 403):
        # 403 par body mein asal wajah hoti hai — 40104 "verify your account"
        # is waqt isi raaste se aata hai, aur wo 401 se bilkul alag masla hai.
        detail = ""
        try:
            detail = (response.json() or {}).get("status_message") or ""
        except Exception:
            pass
        raise _Unavailable(f"auth/verification failed ({response.status_code}) {detail}".strip())
    if response.status_code == 429:
        raise _Unavailable("rate limited (429)")
    if response.status_code >= 400:
        raise _Unavailable(f"HTTP {response.status_code}")

    try:
        payload = response.json()
    except Exception as exc:
        raise _Unavailable(f"unreadable response: {exc}") from exc

    status = payload.get("status_code")
    # 20000 = Ok. 40xxx account-level masail (funds, verification) HTTP 200 ke
    # saath bhi aa sakte hain, is liye body ka status alag se dekhna zaroori hai.
    if status is not None and status != 20000:
        raise _Unavailable(f"{status} {payload.get('status_message')}")

    cost = float(payload.get("cost") or 0)
    tasks = payload.get("tasks")
    if not isinstance(tasks, list):
        raise _Unavailable("no tasks in response")

    items: list[dict] = []
    for task in tasks:
        if task.get("status_code", 0) >= 40000:
            raise _Unavailable(f"task {task.get('status_code')} {task.get('status_message')}")
        for result in task.get("result") or []:
            if not isinstance(result, dict):
                continue
            # Labs endpoints natija `result[].items[]` mein dete hain,
            # Google Ads seedha `result[]` mein.
            nested = result.get("items")
            if isinstance(nested, list):
                items.extend(i for i in nested if isinstance(i, dict))
            else:
                items.append(result)
    return items, cost


def _dig(item: dict, *path):
    """Nested key nikaalo, kahin bhi None mile to None."""
    current = item
    for key in path:
        if not isinstance(current, dict):
            return None
        current = current.get(key)
    return current


def _keyword_of(item: dict) -> str | None:
    value = item.get("keyword") or _dig(item, "keyword_data", "keyword")
    return normalize_keyword(str(value)) if value else None


